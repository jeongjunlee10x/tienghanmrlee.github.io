const data=fs.readFileSync('mrlee-culture-v13-data.js','utf8');
const m=JSON.parse(fs.readFileSync('assets/culture/traffic-v44-published.json','utf8'));
assert.equal(m.topic,'an-toan-giao-thong');
assert.equal(m.photos.length,5);
assert.equal((html.match(/id="cultureImagesV19Topic22"/g)||[]).length,1);
assert(html.includes("dataset.mrleeTrafficGallery='1'"));
assert(html.includes('traffic-gallery-v1.css'));
