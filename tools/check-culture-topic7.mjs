import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const html=fs.readFileSync('van-hoa-bai-hoc.html','utf8');
const engine=fs.readFileSync('mrlee-culture-hd-v19.js','utf8');
const base=fs.readFileSync('mrlee-culture-v13-data.js','utf8');
const css=fs.readFileSync('assets/culture/travel-gallery-v1.css','utf8');
const manifest=JSON.parse(fs.readFileSync('assets/culture/travel-v31-published.json','utf8'));
assert.equal(manifest.photos.length,5);
const refs=[...html.matchAll(/src="(images\/culture-v31-photo\/du-lich\/(\d\d)\.webp)\?v=20261101-topic07-hd31"/g)];
assert.deepEqual(refs.map(x=>x[2]),['01','02','03','04','05']);
assert(html.includes('id="cultureImagesV19Topic7"'));
assert(html.includes("dataset.mrleeTravelGallery='1'"));
assert(engine.includes("const NEW_V31=new Set(['du-lich'])"));
assert(engine.includes("NEW_V31.has(id)?V31"));
assert(base.includes('"image":"images/culture-v31-photo/du-lich/01.webp"'));
assert(css.includes('object-fit:cover!important'));
assert(!html.includes('bộ V25 sử dụng 5 cảnh cắt gốc'));
for(const p of manifest.photos){
 const index=String(p.index).padStart(2,'0');
 assert(refs[p.index-1][1]===p.file);
 assert(p.source_dimensions[0]>=2048&&p.source_dimensions[1]>=1365);
 assert.equal(p.width,1536);assert.equal(p.height,1024);
 const content=fs.readFileSync(p.file);
 assert.equal(content.toString('ascii',0,4),'RIFF');
 assert.equal(content.toString('ascii',8,12),'WEBP');
 assert.equal(content.length,p.bytes);
 assert.equal(crypto.createHash('sha256').update(content).digest('hex'),p.sha256);
 assert(html.includes('Ảnh: '+p.author));
 assert(html.includes(p.licence_url)&&html.includes(p.source_page));
}
for(const n of [3,4,5,6])assert(html.includes('id="cultureImagesV19Topic'+n+'"'));
console.log('PASS Culture 07 HD31: five real landscape photos 1536x1024, photo credits, dimensions, SHA256, and source mapping');
