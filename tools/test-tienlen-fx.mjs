/* Visual effects do not mutate scoring, deck rules or reveal opponents. */
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {analyze,deck} from "../assets/arena/tienlen-engine.js";
import {chopTitle} from "../assets/arena/tienlen-fx.js";
const cards=ids=>ids.map(id=>deck().find(c=>c.id===id));
const two=analyze(cards(["15-0"]));
const pairTwo=analyze(cards(["15-0","15-1"]));
const quad=analyze(cards(["8-0","8-1","8-2","8-3"]));
const six=analyze(cards(["3-0","3-1","4-0","4-1","5-0","5-1"]));
const eight=analyze(cards(["4-0","4-1","5-0","5-1","6-0","6-1","7-0","7-1"]));
assert.equal(chopTitle(two,quad),"TỨ QUÝ CHẶT!");
assert.equal(chopTitle(two,six),"ĐÔI THÔNG CHẶT!");
assert.equal(chopTitle(pairTwo,eight),"ĐÔI THÔNG CHẶT!");
assert.equal(chopTitle(six,quad),"TỨ QUÝ CHẶT!");
assert.equal(chopTitle(null,quad),"");
assert.equal(chopTitle(quad,quad),"");
const fx=await readFile(new URL("../assets/arena/tienlen-fx.js",import.meta.url),"utf8");
const ui=await readFile(new URL("../assets/arena/tienlen-ui.js",import.meta.url),"utf8");
const css=await readFile(new URL("../assets/arena/tienlen-live.css",import.meta.url),"utf8");
const html=await readFile(new URL("../mrlee-game-arena.html",import.meta.url),"utf8");
assert.match(fx,/const visualDeals=52/);
assert.match(fx,/i<visualDeals/);
assert.match(fx,/animate\(sprite/);
assert.match(fx,/playingCard\(card\)/);
assert.match(ui,/fx\.throwCards/);
assert.match(ui,/fx\.deal/);
assert.match(ui,/cardBack\(\)/);
assert.match(ui,/getGold\(\)/);
assert.match(css,/prefers-reduced-motion/);
assert.match(html,/data-fx-phase="idle"/);
assert.doesNotMatch(fx+ui,/service_role|supabase\.from|update.*student_score/i);
console.log("PASS visual FX unit: chop labels, 52 deal flights, card-to-center and demo-only wallet.");
