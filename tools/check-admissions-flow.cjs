'use strict';
const fs=require('node:fs');const assert=require('node:assert/strict');const {execFileSync}=require('node:child_process');
const core=require('../assets/admissions/fit-core.js');
const data=JSON.parse(fs.readFileSync('university-map/universities.json','utf8'));
assert.ok(Array.isArray(data.schools)&&data.schools.length>500,'School source missing');
const profile=core.normalizeProfile({goal:'college',stage:'graduated',region:'busan',korean:'topik12',field:'business'});
assert.equal(profile.goal,'college');assert.equal(profile.region,'busan');
const college=core.recommend(data.schools,profile,6);
assert.ok(college.items.length>0);
assert.ok(college.items.every(s=>s.type==='college'),'Must never label universities as colleges');
assert.ok(college.items.every(s=>!s.ko.includes('대학원')),'Exclude graduate schools from college suggestions');
assert.ok(college.items.some(s=>s.region==='busan'),'Preferred region must be represented');
const uni=core.recommend(data.schools,{goal:'university',region:'seoul'},6);
assert.ok(uni.items.length>0&&uni.items.every(s=>s.type==='university'));
const grad=core.recommend(data.schools,{goal:'graduate',region:'all'},6);
assert.ok(grad.items.every(s=>s.type==='university'),'Do not confuse graduate schools with junior colleges');
const undecided=core.recommend(data.schools,{goal:'undecided',region:'all'},6);
assert.ok(undecided.items.some(s=>s.type==='college')&&undecided.items.some(s=>s.type==='university'),'Exploratory list needs both degree levels');
const unsafe=core.normalizeProfile({goal:'fake',region:'../../secret',stage:'secret',field:'PII',korean:'secret'});
assert.equal(unsafe.goal,'undecided');assert.equal(unsafe.region,'all');
const sample=core.recommend([{id:'a',ko:'경희대학교 대학원',en:'Graduate School of Kyung Hee University',type:'college',campuses:[{region:'seoul'}]},{id:'b',ko:'부산대학교',en:'Pusan National University',type:'university',campuses:[{region:'busan'}]}],{goal:'college'});
assert.equal(sample.items.length,0,'Misclassified graduate program must not appear as college');
const html=fs.readFileSync('tuyen-sinh.html','utf8');
const css=fs.readFileSync('assets/admissions/entry.css','utf8');
const js=fs.readFileSync('assets/admissions/entry.js','utf8');
const interview=fs.readFileSync('on-luyen-phong-van.html','utf8');
const interviewCss=fs.readFileSync('assets/branding/interview-readability.css','utf8');
for(const id of ['mrleeAdmissionsDialog','mrleeAdmissionsForm','apStep1','apStep2','apFinish','mrleeAdmissionsResults','apSchools','apRetake']){
 assert.ok(html.includes('id="'+id+'"'),'Missing admissions element: '+id);
}
assert.match(html,/assets\/admissions\/entry\.js/);
assert.match(html,/assets\/admissions\/fit-core\.js/);
assert.doesNotMatch(html,/id="tsWizard"/,'Do not render duplicate on-page admission questionnaire');
assert.ok(js.includes('sessionStorage.setItem(store')&&js.includes('new FormData(form)'));
assert.ok(js.includes('history.replaceState')&&js.includes('mrleeAdmissionsDone'));
assert.ok(js.includes('textContent=item.name')&&!js.includes('innerHTML=item.name'),'Escaped school names must be rendered safely');
assert.match(css,/::backdrop/);assert.match(css,/@media\(max-width:520px\)/);
assert.match(interview,/body class="mrlee-interview-page"/);
assert.match(interview,/interview-readability\.css/);
assert.match(interviewCss,/html\[data-mrlee-theme="future"\] body\.mrlee-interview-page/);
for(const p of ['assets/admissions/entry.js','assets/admissions/fit-core.js'])execFileSync(process.execPath,['--check',p]);
console.log('PASS admissions: catalog-backed school type safety, 2-step modal, non-PII preferences, mobile CSS and interview theme protection.');
